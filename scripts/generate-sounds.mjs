import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import {
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync
} from 'node:fs'
import { join } from 'node:path'

const require = createRequire(import.meta.url)
const ffmpeg = require('ffmpeg-static')
const root = join(process.cwd(), 'resources', 'sounds')
mkdirSync(root, { recursive: true })

const sounds = [
  {
    id: 'whoosh-air',
    name: '空气掠过',
    category: 'Whoosh',
    seconds: 0.6,
    input: 'anoisesrc=color=pink:duration=0.6:sample_rate=44100',
    filter:
      'highpass=f=400,lowpass=f=3500,afade=t=in:d=0.05,afade=t=out:st=0.35:d=0.25,volume=0.7'
  },
  {
    id: 'impact-low',
    name: '低频撞击',
    category: 'Impact',
    seconds: 0.45,
    input: 'sine=frequency=70:duration=0.45:sample_rate=44100',
    filter: 'afade=t=out:st=0.03:d=0.4,volume=0.9'
  },
  {
    id: 'riser-up',
    name: '上升音效',
    category: 'Riser',
    seconds: 1,
    input:
      "aevalsrc='sin(2*PI*(200+900*t)*t)*0.35':d=1.0:s=44100",
    filter: 'afade=t=in:d=0.1,afade=t=out:st=0.8:d=0.2,volume=0.8'
  },
  {
    id: 'click-ui',
    name: '点击',
    category: 'Click',
    seconds: 0.08,
    input: 'anoisesrc=color=white:duration=0.08:sample_rate=44100',
    filter: 'highpass=f=1800,afade=t=out:st=0.01:d=0.06,volume=0.6'
  },
  {
    id: 'success-chime',
    name: '完成提示',
    category: 'Chime',
    seconds: 0.4,
    input: 'sine=frequency=660:duration=0.4:sample_rate=44100',
    filter: 'afade=t=out:st=0.08:d=0.3,volume=0.55'
  },
  {
    id: 'alert-buzz',
    name: '警告低鸣',
    category: 'Alert',
    seconds: 0.45,
    input: 'sine=frequency=120:duration=0.45:sample_rate=44100',
    filter: 'tremolo=f=12:d=0.4,afade=t=out:st=0.15:d=0.28,volume=0.7'
  }
]

const manifest = { version: 1, sounds: [] }

for (const sound of sounds) {
  const file = `${sound.id}.wav`
  const output = join(root, file)
  execFileSync(
    ffmpeg,
    [
      '-y',
      '-f',
      'lavfi',
      '-i',
      sound.input,
      '-af',
      sound.filter,
      '-c:a',
      'pcm_s16le',
      '-ar',
      '44100',
      '-ac',
      '1',
      output
    ],
    { stdio: 'inherit' }
  )

  const bytes = readFileSync(output)
  manifest.sounds.push({
    id: sound.id,
    name: sound.name,
    category: sound.category,
    file,
    duration: sound.seconds,
    bytes: statSync(output).size,
    license: 'CC0-1.0',
    source: 'generated by CineLab',
    sha256: createHash('sha256').update(bytes).digest('hex')
  })
}

writeFileSync(
  join(root, 'manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8'
)
console.log(
  JSON.stringify({
    root,
    sounds: manifest.sounds.length,
    bytes: manifest.sounds.reduce((sum, sound) => sum + sound.bytes, 0)
  })
)
